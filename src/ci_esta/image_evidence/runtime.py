"""
Portable runtime inspection. Keep this module stdlib-only for frozen observers.

Consumer policy selects roots and required modules. This module owns exact file
identity and CPython content validation, including source paths and cache headers.
"""

from __future__ import annotations

import hashlib
import importlib.util
import marshal
import stat
import struct
from pathlib import Path
from types import CodeType
from typing import TypedDict


def validate_bytecode(source: Path) -> None:
    """Reject missing, stale, or differently located compiled application/dependency code."""
    compiled = Path(importlib.util.cache_from_source(str(source))).read_bytes()
    data = source.read_bytes()
    assert compiled[:4] == importlib.util.MAGIC_NUMBER, f"Wrong bytecode version: {source}"
    flags = struct.unpack("<I", compiled[4:8])[0]
    if flags & 1:
        assert compiled[8:16] == importlib.util.source_hash(data), f"Stale bytecode hash: {source}"
    else:
        mtime, size = struct.unpack("<II", compiled[8:16])
        assert mtime == int(source.stat().st_mtime) & 0xFFFFFFFF, f"Stale bytecode mtime: {source}"
        assert size == len(data) & 0xFFFFFFFF, f"Stale bytecode size: {source}"
    code = marshal.loads(compiled[16:])
    assert isinstance(code, CodeType), f"Bytecode must contain a module: {source}"
    assert code.co_filename == str(source), f"Compiled code or embedded source path differs: {source}"
    assert code == compile(data, str(source), "exec", dont_inherit=True), (
        f"Compiled code or embedded source path differs: {source}"
    )


class FileFingerprint(TypedDict):
    """Runtime file identity; timestamps and installer bookkeeping are not behavior."""

    mode: int
    sha256: str | None
    symlink: str | None


def file_inventory(root: Path, *, installed: bool = False, recursive: bool = True) -> dict[str, FileFingerprint]:
    """Hash runtime contents, retaining distribution metadata and executable scripts."""
    result: dict[str, FileFingerprint] = {}
    for path in sorted(root.rglob("*") if recursive else root.iterdir()):
        relative = path.relative_to(root)
        if not path.is_file() and not path.is_symlink():
            continue
        if installed and ("__pycache__" in relative.parts or path.suffix == ".pyc"):
            continue
        if installed and path.parent.name.endswith(".dist-info") and path.name in {"RECORD", "uv_cache.json"}:
            # RECORD includes generated bytecode hashes; uv_cache is installer
            # bookkeeping. Validate bytecode separately, compare runtime metadata.
            continue
        result[str(relative)] = {
            "mode": stat.S_IMODE(path.lstat().st_mode),
            "sha256": None if path.is_symlink() else hashlib.sha256(path.read_bytes()).hexdigest(),
            "symlink": str(path.readlink()) if path.is_symlink() else None,
        }
    return result
