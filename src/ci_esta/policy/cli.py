"""JSON boundary for any test runner. Invalid input never leaves a reusable plan."""

import argparse
import json
import os
import sys
from pathlib import Path

import yaml
from pydantic import TypeAdapter

from ci_esta.policy import ExecutionPlan, Policy, Request, Work, plan


def affected_ids(value: str) -> frozenset[str] | None:
    """Consume a native selector's IDs or its complete lane-to-boolean mapping."""
    data = json.loads(value)
    if data is None:
        return None
    if isinstance(data, dict) and all(isinstance(key, str) and type(flag) is bool for key, flag in data.items()):
        return frozenset(key for key, flag in data.items() if flag)
    if isinstance(data, list) and all(isinstance(item, str) for item in data):
        return frozenset(data)
    raise ValueError("affected must be null, a list of IDs, or a complete ID-to-boolean mapping")


def write_outputs(result: ExecutionPlan, output: str) -> None:
    values = {
        "admitted": {item.work.id: item.status == "run" for item in result.decisions},
        "fresh": {item.work.id: item.fresh for item in result.decisions},
        "count": len(result.runnable),
        "plan": result.model_dump(mode="json"),
    }
    if output:
        with Path(output).open("a", encoding="utf-8") as stream:
            for key, value in values.items():
                stream.write(f"{key}={json.dumps(value, separators=(',', ':'))}\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--policy", required=True)
    parser.add_argument("--profile", default="legacy")
    parser.add_argument("--occasion", choices=["pr", "push", "schedule", "deployment", "manual"], required=True)
    parser.add_argument("--revision", required=True)
    parser.add_argument("--environment")
    parser.add_argument("--deployed-revision")
    parser.add_argument("--affected", default="null")
    parser.add_argument("--requested", default="null")
    parser.add_argument("--inventory", help="Optional JSON inventory generated by a runner adapter")
    parser.add_argument("--output", default="test-policy-plan.json")
    parser.add_argument("--github-output", default=os.environ.get("GITHUB_OUTPUT", ""))
    args = parser.parse_args(argv)
    destination = Path(args.output)
    # A failed invocation must not leave a previous successful plan for an executor.
    destination.unlink(missing_ok=True)
    try:
        policy = Policy.model_validate(yaml.safe_load(Path(args.policy).read_text(encoding="utf-8")))
        requested = json.loads(args.requested)
        if requested is not None and (
            not isinstance(requested, list) or not all(isinstance(item, str) for item in requested)
        ):
            raise ValueError("requested must be null or a list of work IDs")
        inventory = (
            TypeAdapter(tuple[Work, ...]).validate_json(Path(args.inventory).read_text())
            if args.inventory
            else policy.work
        )
        raw_affected = json.loads(args.affected)
        # A partial boolean map is unknown evidence, not proof that omitted lanes are unaffected.
        if isinstance(raw_affected, dict) and set(raw_affected) != {item.id for item in inventory}:
            raise ValueError("affected mapping must account for every inventory work ID")
        request = Request(
            profile=args.profile,
            occasion=args.occasion,
            revision=args.revision,
            environment=args.environment or None,
            deployed_revision=args.deployed_revision or None,
            affected=affected_ids(args.affected),
            requested=requested,
        )
        result = plan(policy, request, inventory)
        destination.write_text(result.model_dump_json(indent=2) + "\n", encoding="utf-8")
        write_outputs(result, args.github_output)
        for item in result.decisions:
            print(f"{item.work.id}: {item.status}: {item.reason}")
        if result.unavailable:
            print("Admitted work has unavailable prerequisites; no pass is claimed.", file=sys.stderr)
            return 1
        return 0
    except (OSError, ValueError, yaml.YAMLError) as error:
        print(f"Policy planning failed: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
